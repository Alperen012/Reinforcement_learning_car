"""Evaluate every finished benchmark run plus baselines and write docs/results.md.

    python scripts/make_results.py            # after scripts/run_benchmarks.ps1

Each trained agent (best checkpoint of each seed) and each baseline drives the
same seeded episodes. Numbers are mean ± std *across seeds* of the per-seed
mean, so the spread shows how much the result depends on the training seed.
"""

from __future__ import annotations

import json
import platform
import sys
from dataclasses import replace
from pathlib import Path

import numpy as np

from racing_gym.config import EnvConfig, load_config
from racing_gym.evaluation import TEST_SEED, make_policy, run_episodes, summarize
from racing_gym.plotting import plot_runs
from racing_gym.track import make_track

ROOT = Path(__file__).resolve().parents[1]
RUNS = ROOT / "runs"
ASSETS = ROOT / "docs" / "assets"
EPISODES = 10
ALGOS = ["ppo_classic", "a2c_classic", "sac_classic", "td3_classic", "dqn_classic"]
UNSEEN = ["random:0", "random:1", "random:2", "random:3", "random:4", "hairpin", "snake"]


def evaluate(spec: str, env_cfg: EnvConfig, tracks: list[str], algo: str = "ppo", episodes: int = EPISODES):
    policy, pol_env, _ = make_policy(spec, env_cfg, algo=algo)
    return summarize(run_episodes(policy, pol_env, tracks, episodes=episodes, seed=TEST_SEED))


def per_seed(exp: str, env_cfg: EnvConfig, tracks: list[str], episodes: int = EPISODES, model: str = ""):
    """``model=""`` evaluates best_model.zip; ``model="final_model.zip"`` the last weights."""
    rows, metas = [], []
    for seed_dir in sorted((RUNS / exp).glob("seed*")):
        if not (seed_dir / "run.json").exists():
            continue
        rows.append(evaluate(str(seed_dir / model) if model else str(seed_dir), env_cfg, tracks, episodes=episodes))
        metas.append(json.loads((seed_dir / "run.json").read_text()))
    return rows, metas


def fmt(rows, key, pct=False, d=1):
    v = np.array([r[key] for r in rows])
    if pct:
        return f"{100 * v.mean():.0f}%" + (f" ± {100 * v.std():.0f}" if len(v) > 1 else "")
    return f"{v.mean():.{d}f}" + (f" ± {v.std():.{d}f}" if len(v) > 1 else "")


def table(header, lines):
    out = ["| " + " | ".join(header) + " |", "|" + "---|" * len(header)]
    out += ["| " + " | ".join(str(c) for c in line) + " |" for line in lines]
    return "\n".join(out)


def main():
    env_cfg = replace(EnvConfig(track="classic"), random_start=True)
    lap_px = make_track("classic").length
    md = ["# Results", "",
          "Generated by `python scripts/make_results.py` from the runs produced by "
          "`scripts/run_benchmarks.ps1`. Every number below is computed by the script.", "",
          "## Method", "",
          f"* Hardware: {platform.processor() or platform.machine()}, CPU only (PyTorch CPU build).",
          f"* **Test episodes:** {EPISODES} per agent on `classic`, random start points (reset seeds "
          f"{TEST_SEED}+), max 2000 steps, deterministic actions. Every agent and baseline drives the same "
          "episodes.",
          "* **Checkpoint selection (validation):** during training each checkpoint drives the same "
          "evenly spread validation start points; the one with the highest validation return is kept "
          "(`best_model.zip`). Test start points are drawn so that they never coincide with a validation "
          "point, so no reported episode was used to choose a checkpoint. The track itself is the same: "
          "this table measures driving `classic` well, not generalising (see the last section).",
          "* **Spread:** mean ± std *across training seeds* of each seed's mean.",
          "* **Training time** was measured with two training jobs running in parallel and depends on "
          "machine load: read it as a rough cost, not a precise comparison.",
          "* **Reproducibility:** training is deterministic on CPU. Re-running PPO (3 seeds), SAC (3 seeds) "
          "and the quickstart from scratch gave bit-identical weights.",
          f"* **Ceiling:** flat out (8 px/step) along the centre line, 2000 steps are "
          f"{2000 * 8 / lap_px:.1f} laps of `classic` ({lap_px:.0f} px). Good agents do a little better by "
          "taking the inside of bends (progress is measured on the centre line). Laps are counted "
          "whole, so differences near the ceiling are coarse.", ""]

    # ---------------------------------------------------------------- algorithms on classic
    lines, summary, finals = [], {}, {}
    for spec, name in [("random", "random actions"), ("untrained", "untrained PPO network"),
                       ("heuristic", "hand-written controller")]:
        r = evaluate(spec, env_cfg, ["classic"])
        summary[spec] = [r]
        lines.append([name, "—", "—", "—", fmt([r], "return_mean"), fmt([r], "laps_mean", d=2),
                      fmt([r], "crash_rate", pct=True), fmt([r], "avg_speed", d=2), "—", "—", "—"])
    gaps = []
    for exp in ALGOS:
        rows, metas = per_seed(exp, env_cfg, ["classic"])
        if not rows:
            continue
        cfg = load_config(RUNS / exp / "seed0" / "config.toml")
        algo = cfg.algo.upper()
        summary[algo] = rows
        final, _ = per_seed(exp, env_cfg, ["classic"], model="final_model.zip")
        finals[algo] = final
        best_steps = [m.get("best_timesteps") for m in metas]
        lines.append([f"**{algo}**", len(rows), f"{cfg.train.total_timesteps:,}",
                      ", ".join(f"{t // 1000}k" for t in best_steps if t is not None) or "?",
                      fmt(rows, "return_mean"), fmt(rows, "laps_mean", d=2), fmt(rows, "crash_rate", pct=True),
                      fmt(rows, "avg_speed", d=2), fmt(final, "laps_mean", d=2), fmt(final, "crash_rate", pct=True),
                      f"{np.mean([m['train_seconds'] for m in metas]) / 60:.1f} min"])
        val = np.mean([m["best_eval_return"] for m in metas])
        test = np.mean([r["return_mean"] for r in rows])
        gaps.append([algo, f"{val:.1f}", f"{test:.1f}", f"{test - val:+.1f}"])
    md += ["## Algorithms on the `classic` track", "",
           table(["policy", "seeds", "training budget (steps)", "best checkpoint (step, per seed)", "return",
                  "laps", "crash rate", "avg speed", "laps, final weights", "crash rate, final weights",
                  "train time / seed"], lines), "",
           "The first columns use each seed's best checkpoint. The *final weights* columns use the network "
           "at the end of the training budget: where they are much worse, training was unstable and the "
           "best checkpoint hides it (see the curves below).", "",
           "![validation return during training](assets/algorithms.png)", ""]
    plot_runs([str(RUNS / e) for e in ALGOS if (RUNS / e).exists()], ASSETS / "algorithms.png",
              title="Validation return during training (classic track; band = min..max over seeds)")

    # What the table does and does not say, derived from the numbers above.
    algos = [a for a in summary if a.isupper()]
    laps = {a: np.array([r["laps_mean"] for r in summary[a]]) for a in algos}
    crash = {a: np.mean([r["crash_rate"] for r in summary[a]]) for a in algos}
    h = summary["heuristic"][0]
    better = [a for a in algos if laps[a].mean() > h["laps_mean"] and crash[a] <= h["crash_rate"]]
    worse = [a for a in algos if a not in better]
    ranked = sorted(algos, key=lambda a: -laps[a].mean())
    unstable = [f"{a} ({np.mean([r['crash_rate'] for r in finals[a]]):.0%} crashes)" for a in algos
                if np.mean([r["crash_rate"] for r in finals[a]]) > 0.1]
    ties = [f"{a} and {b}" for a, b in zip(ranked, ranked[1:])
            if laps[a].mean() - laps[b].mean() <= max(laps[a].std(), laps[b].std())]
    md += ["### Reading the table", "",
           f"* More laps than the hand-written controller ({h['laps_mean']:.2f}) with no more crashes: "
           f"{', '.join(better) or 'none'}. Not better: {', '.join(worse) or 'none'}. This is about the best "
           "checkpoint of each seed.",
           f"* With the weights left at the end of training, these crash in more than 10% of episodes: "
           f"{', '.join(unstable) or 'none'}. Their learning is unstable, and keeping the best checkpoint "
           "is what makes them look good above.",
           f"* Neighbours in the ranking that differ by less than one standard deviation across seeds "
           f"(treat as ties): {'; '.join(ties) or 'none'}. Three seeds cannot separate close results.",
           "* **Not a like-for-like race.** Budgets differ (off-policy SAC/TD3 get half the steps, "
           "because each step costs more compute), DQN drives with 9 discrete actions instead of "
           "continuous ones, and every algorithm uses Stable-Baselines3 defaults plus the few settings "
           "in `configs/*_classic.toml`: nothing was tuned per algorithm. Tuned, they could rank "
           "differently.", "",
           "### Did checkpoint selection overfit?", "",
           "Return of the selected checkpoint on its validation episodes vs on the test episodes "
           "(mean over seeds). A large negative gap would mean checkpoints were chosen for luck on "
           "the validation start points.", "",
           table(["algorithm", "validation return", "test return", "gap"], gaps), ""]

    # ---------------------------------------------------------------- generalisation
    if (RUNS / "ppo_generalize").exists():
        lines = []
        for spec, name in [("heuristic", "hand-written controller")]:
            r = evaluate(spec, env_cfg, UNSEEN, episodes=3)
            lines.append([name, fmt([r], "laps_mean", d=2), fmt([r], "lap_fraction_mean", d=2),
                          fmt([r], "crash_rate", pct=True)])
        gen = load_config(RUNS / "ppo_generalize" / "seed0" / "config.toml")
        assert not set(gen.train.eval_tracks) & set(UNSEEN), "validation tracks overlap the generalisation test"
        for exp, name, model in [("ppo_classic", "PPO trained on `classic` only, final weights", "final_model.zip"),
                                 ("ppo_generalize", "PPO trained on random tracks, final weights", "final_model.zip"),
                                 ("ppo_generalize", "PPO trained on random tracks, best checkpoint", "")]:
            rows, _ = per_seed(exp, env_cfg, UNSEEN, episodes=3, model=model)
            if rows:
                lines.append([f"{name} ({len(rows)} seeds)", fmt(rows, "laps_mean", d=2),
                              fmt(rows, "lap_fraction_mean", d=2), fmt(rows, "crash_rate", pct=True)])
        md += ["## Generalisation", "",
               "Evaluated on tracks never used for training or validation: "
               f"{', '.join(f'`{t}`' for t in UNSEEN)} (3 episodes each). Training uses procedural tracks "
               "with seeds of 1000 and above; validation used "
               f"{', '.join(f'`{t}`' for t in gen.train.eval_tracks)} (disjoint from the test tracks; checked "
               "by the script). \"Final weights\" involve no checkpoint choice at all.", "",
               table(["policy", "laps", "laps incl. partial", "crash rate"], lines), ""]

    md += ["## Reproduce", "", "```bash", "pip install -e .", "./scripts/run_benchmarks.ps1   # or run the "
           "`racing-gym train -c configs/<name>.toml` lines by hand",
           "python scripts/reselect_best.py runs/<name>   # only for runs trained before v0.3",
           "python scripts/make_results.py", "```", ""]
    (ROOT / "docs" / "results.md").write_text("\n".join(md), encoding="utf-8")
    print("\n".join(md))


if __name__ == "__main__":
    sys.exit(main())
